// Helper to generate realistic subject scores
export const generateAcademicRecords = (students: Student[]): Record<string, StudentAcademicRecord> => {
  const records: Record<string, StudentAcademicRecord> = {};

  students.forEach((s) => {
    let base = 7.5;
    if (s.id === 's-001') base = 8.6; // Nguyễn Minh Anh
    if (s.id === 's-002') base = 5.2; // Phạm Gia Huy
    if (s.id === 's-003') base = 6.4; // Trần Mai Chi
    if (s.id === 's-004') base = 6.6; // Võ Ngọc Bảo
    if (s.id === 's-005') base = 5.6; // Lê Minh Khang
    if (s.id === 's-006') base = 9.1; // Đỗ Khánh Vy
    if (s.id === 's-007') base = 7.9; // Hoàng Đức Anh
    if (s.id === 's-008') base = 8.4; // Trần Hoàng Nam

    const scores: Record<string, any> = {};
    let totalScore = 0;
    let totalWeight = 0;

    SUBJECTS.forEach((sub) => {
      // Deterministic slight variations based on student code and subject code
      const hash = (s.studentCode.charCodeAt(5) || 0) + (sub.code.charCodeAt(0) || 0);
      const var1 = ((hash % 15) - 7) / 10;
      let tx1 = Math.min(10, Math.max(3.5, Number((base + var1).toFixed(1))));
      let tx2 = Math.min(10, Math.max(3.5, Number((base - var1 * 0.5).toFixed(1))));
      let gk = Math.min(10, Math.max(3.5, Number((base + var1 * 0.7).toFixed(1))));
      let ck = Math.min(10, Math.max(3.5, Number((base + 0.2).toFixed(1))));

      // Special overrides for requested students
      if (s.id === 's-001' && sub.id === 'eng') {
        tx1 = 8.5; tx2 = 9.0; gk = 8.8; ck = 9.2;
      }
      if (s.id === 's-002' && sub.id === 'math') {
        tx1 = 4.5; tx2 = 4.0; gk = 4.2; ck = 4.8;
      }
      if (s.id === 's-008' && sub.id === 'math') {
        tx1 = 8.5; tx2 = 9.0; gk = 8.5; ck = 9.5;
      }

      const tbm = Number(((tx1 + tx2 + gk * 2 + ck * 3) / 7).toFixed(1));
      scores[sub.id] = {
        subjectId: sub.id,
        subjectName: sub.name,
        tx1,
        tx2,
        gk,
        ck,
        tbm,
      };

      totalScore += tbm * sub.coefficient;
      totalWeight += sub.coefficient;
    });

    const gpa = Number((totalScore / totalWeight).toFixed(1));
    let rank: 'Giỏi' | 'Khá' | 'Trung bình' | 'Yếu' = 'Khá';
    if (gpa >= 8.0) rank = 'Giỏi';
    else if (gpa >= 6.5) rank = 'Khá';
    else if (gpa >= 5.0) rank = 'Trung bình';
    else rank = 'Yếu';

    let trend: 'up' | 'down' | 'stable' = 'stable';
    if (s.id === 's-001' || s.id === 's-007' || s.id === 's-008') trend = 'up';
    if (s.id === 's-002' || s.id === 's-005') trend = 'down';

    records[s.id] = {
      studentId: s.id,
      semester: 'HK1',
      scores,
      gpa,
      rank,
      trend,
      previousGpa: Number((gpa + (trend === 'up' ? -0.4 : trend === 'down' ? 0.5 : 0)).toFixed(1)),
    };
  });

  return records;
};

